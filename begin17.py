A = int(input("Введите первую точку: "))
B = int(input("Введите вторую точку: "))
C = int(input("Введите третью точку: "))
ac = abs(C - A)
bc = abs(C - B)
abc = abs(ac + bc)
print(f"Расстояние от точки A до точки C равно: {ac}, расстояние от точки B до точки C равно: {bc}, их сумма равна: {abc}")